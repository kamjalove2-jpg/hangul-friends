const place = (strokes, [bx, by, bw, bh]) =>
  strokes.map((s) => s.map(([x, y]) => [bx + (x / 100) * bw, by + (y / 100) * bh]));

function jamoStrokes(j) {
  if (JAMO[j]) return JAMO[j];
  const dbl = { 'ㄲ': 'ㄱ', 'ㄸ': 'ㄷ', 'ㅃ': 'ㅂ', 'ㅆ': 'ㅅ', 'ㅉ': 'ㅈ' }[j];
  if (dbl) return [...place(JAMO[dbl], [0, 0, 52, 100]), ...place(JAMO[dbl], [48, 0, 52, 100])];
  return null;
}

export function syllableParts(ch) {
  const code = ch.charCodeAt(0) - 0xac00;
  if (code < 0 || code > 11171) return null;
  return { cho: CHO[Math.floor(code / 588)], jung: JUNG[Math.floor((code % 588) / 28)], jong: JONG[code % 28] };
}

export function syllableStrokes(ch) {
  const p = syllableParts(ch);
  if (!p) return null;
  const cs = jamoStrokes(p.cho), vs = jamoStrokes(p.jung), fs = p.jong ? jamoStrokes(p.jong) : null;
  if (!cs || !vs || (p.jong && !fs)) return null;
  const horiz = 'ㅗㅛㅜㅠㅡ'.includes(p.jung);
  let bc, bv, bf;
  if (horiz) {
    if (fs) { bc = [8, 0, 84, 36]; bv = [0, 34, 100, 32]; bf = [12, 64, 76, 36]; }
    else { bc = [8, 0, 84, 54]; bv = [0, 50, 100, 50]; }
  } else if (fs) { bc = [0, 2, 52, 56]; bv = [34, 2, 66, 56]; bf = [12, 58, 76, 42]; }
  else { bc = [0, 8, 54, 84]; bv = [34, 8, 66, 84]; }
  return [...place(cs, bc), ...place(vs, bv), ...(fs ? place(fs, bf) : [])];
}

export function compose(cho, jung) {
  const a = CHO.indexOf(cho), b = JUNG.indexOf(jung);
  if (a < 0 || b < 0) return '';
  return String.fromCharCode(0xac00 + (a * 21 + b) * 28);
}
